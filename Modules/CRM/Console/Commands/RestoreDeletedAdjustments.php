        app()->instance('crm.suppress_outbound_push', true);

        $inserted = 0;
        $skipped = 0;

        foreach ($data as [$techId, $amount, $createdAt, $note]) {
            // اطمینان از وجود تکنسین
            $exists = DB::table('crm_technicians')->where('id', $techId)->exists();
            if (! $exists) {
                $skipped++;
                continue;
            }

            DB::table('crm_tech_wallet_transactions')->insert([
                'technician_id' => $techId,
                'order_id' => null,
                'invoice_id' => null,
                'wp_id' => null,
                'type' => 'adjustment',
                'amount' => $amount,
                'balance_after' => 0, // بعد توسط recompute درست می‌شود
                'note' => $note,
                'created_by' => null,
                'created_at' => $createdAt,
                'updated_at' => now(),
            ]);
            $inserted++;
        }

        $this->info("✓ {$inserted} تراکنش بازگردانده شد.");
        if ($skipped > 0) {
            $this->warn("رد شده (تکنسین موجود نبود): {$skipped}");
        }

        if ($this->option('recompute')) {
            $this->info('در حال recompute balances...');
            Artisan::call('crm:wallet:recompute-balances');
            $this->info('✓ موجودی‌ها بازخوانی شدند.');
        } else {
            $this->warn('گام بعدی: php artisan crm:wallet:recompute-balances');
        }

        return self::SUCCESS;
    }
