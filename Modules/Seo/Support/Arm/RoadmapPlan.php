            ['فهرست شکاف‌های نهایی'], ['هر انتشار روزهای ۸۵–۹۰ به یک شکاف مستند وصل باشد']);
        $add(86, 'تقویت برنده‌ها (Winners)', 'content_refresh', 'p0',
            'محتواها/صفحاتی که بیشترین رشد را داشتند، با محتوای تکمیلی و لینک تقویت شوند.',
            ['فهرست برنده‌ها + اقدامات تقویتی'], ['برای هر برنده حداقل یک اقدام ثبت شود']);
        $add(88, 'گزارش جامع پایان دوره', 'measurement', 'p0',
            'مقایسهٔ کامل با خط مبنا: کلیک، CTR تجاری، Top3/Top10، لید تماس/اپ.',
            ['گزارش مدیریتی پایان دوره'], ['هر KPI مقدار قبل/بعد دارد']);
        $add(90, 'برنامهٔ فصل بعد (Roadmap Q2)', 'planning', 'p0',
            'تدوین برنامهٔ ۹۰ روزهٔ بعدی بر اساس آموخته‌ها و شکاف‌ها.',
            ['پیش‌نویس roadmap فصل بعد'], ['اولویت‌های p0 فصل بعد مشخص باشند']);

        /* ── cadence تولید محتوا (هفته‌های ۱ تا ۱۲) ─────────────────────── */
        foreach (self::contentCadence() as $item) {
            $add($item['day'], $item['title'], $item['type'], $item['priority'], $item['desc'],
                $item['deliverables'], $item['acceptance']);
        }

        usort($out, fn ($a, $b) => [$a['day_number'], $a['title']] <=> [$b['day_number'], $b['title']]);

        return $out;
    }

    /**
     * کارهای هفتگی تولید/به‌روزرسانی محتوا طبق cadence نامه.
     *
     * @return list<array<string, mixed>>
     */
    private static function contentCadence(): array
    {
        $plan = [
            // هفته => [new, refresh, service_optimization, internal_link_sprint]
            1 => [1, 2, 0, false],
            2 => [2, 2, 1, false],
            3 => [2, 3, 1, false],
            4 => [2, 3, 1, false],
            5 => [3, 3, 0, true],
            6 => [3, 3, 0, true],
            7 => [3, 3, 1, true],
            8 => [3, 3, 1, true],
            9 => [3, 3, 1, false],
            10 => [4, 3, 0, false],
            11 => [3, 3, 1, false],
            12 => [4, 3, 1, false],
        ];

        $out = [];
        foreach ($plan as $week => [$new, $refresh, $serviceOpt, $sprint]) {
            [$cluster, $focus] = self::WEEK_THEMES[$week];
            $base = ($week - 1) * 7;

            for ($i = 1; $i <= $new; $i++) {
                $out[] = [
                    'day' => min(90, $base + 1 + ($i - 1) * 2),
                    'title' => "محتوای جدید {$i}/{$new} هفته {$week} — خوشهٔ {$cluster}",
                    'type' => 'content_new',
                    'priority' => $week <= 2 ? 'p0' : 'p1',
                    'desc' => "تولید محتوای جدید در {$focus}. موضوع دقیق از شکاف‌های نگاشت کلمات همان هفته انتخاب می‌شود؛ هر محتوا کلمهٔ primary یکتا، بریف، outline و لینک داخلی به صفحهٔ خدمات خوشه دارد.",
                    'deliverables' => ['بریف تأییدشده', 'پیش‌نویس کامل', 'لینک داخلی به صفحهٔ خدمات '.$cluster],
                    'acceptance' => ['کلمهٔ primary بدون هم‌نوع‌خواری', 'عبور از بازبینی تخصصی و سئو'],
                ];
            }
            for ($i = 1; $i <= $refresh; $i++) {
                $out[] = [
                    'day' => min(90, $base + 2 + ($i - 1) * 2),
                    'title' => "به‌روزرسانی محتوا {$i}/{$refresh} هفته {$week} — خوشهٔ {$cluster}",
                    'type' => 'content_refresh',
                    'priority' => 'p1',
                    'desc' => "به‌روزرسانی یک محتوای پرایمپرشن {$cluster} از فهرست فرصت‌ها (striking_distance/low_ctr): تازه‌سازی اطلاعات، پاسخ سریع بالای صفحه، پل تجاری به خدمات.",
                    'deliverables' => ['نسخهٔ به‌روزشده', 'ثبت last_content_update'],
                    'acceptance' => ['CTR در پایش ۱۴ روزه افت نکند'],
                ];
            }
            if ($serviceOpt > 0) {
                $out[] = [
                    'day' => min(90, $base + 5),
                    'title' => "بهینه‌سازی صفحهٔ خدمات هفته {$week} — {$cluster}",
                    'type' => 'service_optimization',
                    'priority' => 'p0',
                    'desc' => "بهینه‌سازی یک صفحهٔ تجاری {$cluster} طبق چک‌لیست: Title/H1 هم‌نیت با کوئری، عناصر اعتماد (ضمانت، اعزام)، FAQ، توضیح قیمت، لینک داخلی و CTA تماس/اپ.",
                    'deliverables' => ['صفحهٔ بهینه‌شده', 'چک‌لیست تکمیل‌شده'],
                    'acceptance' => ['بهبود CTR یا رتبه در پایش ۱۴ روزه'],
                ];
            }
            if ($sprint) {
                $out[] = [
                    'day' => min(90, $base + 6),
                    'title' => "اسپرینت لینک داخلی هفته {$week} — {$cluster}",
                    'type' => 'internal_linking',
                    'priority' => 'p1',
                    'desc' => "درج حداقل ۱۰ لینک متنی از مقالات پرقدرت {$cluster} به صفحات خدمات/برند مرتبط با انکرهای متنوع.",
                    'deliverables' => ['۱۰ لینک درج‌شده در فضای لینک‌سازی'],
                    'acceptance' => ['وضعیت همهٔ لینک‌ها placed/live'],
                ];
            }
        }

        return $out;
    }

    private static function phaseOf(int $day): int
    {
        foreach (ArmEnums::PHASES as $num => $phase) {
            if ($day >= $phase['range'][0] && $day <= $phase['range'][1]) {
                return $num;
            }
        }

        return 6;
    }
